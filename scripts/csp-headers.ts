/**
 * Post-build: hash every inline <script> in out/**\/*.html and write a
 * Content-Security-Policy-Report-Only header to out/_headers.
 *
 * Why _headers and not netlify.toml: the hashes change on every build, and
 * netlify.toml is committed. Netlify merges out/_headers with the static
 * [[headers]] in netlify.toml. Switch the header name to
 * Content-Security-Policy once the console is clean on a deploy preview.
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUT_DIR = 'out';
const HEADER_NAME = 'Content-Security-Policy-Report-Only';

// Inline scripts without src. Non-JS types (application/ld+json, application/json) are data blocks
// that CSP does not execute, so they need no hash.
const SCRIPT_RE = /<script(?![^>]*\ssrc=)([^>]*)>([\s\S]*?)<\/script>/gi;
const NON_JS_TYPE_RE = /\stype=["']?(application\/(ld\+)?json)["']?/i;

const htmlFiles = readdirSync(OUT_DIR, { recursive: true, encoding: 'utf8' }).filter((f) =>
  f.endsWith('.html'),
);

if (htmlFiles.length === 0) {
  console.error(`csp-headers: no HTML files in ${OUT_DIR}/. Run next build first.`);
  process.exit(1);
}

const hashes = new Set<string>();
for (const file of htmlFiles) {
  const html = readFileSync(join(OUT_DIR, file), 'utf8');
  for (const match of html.matchAll(SCRIPT_RE)) {
    const [, attrs = '', body = ''] = match;
    if (NON_JS_TYPE_RE.test(attrs) || body.length === 0) continue;
    hashes.add(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
  }
}

const directives = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].sort().join(' ')}`.trim(),
  // next/image and Next's runtime set inline style attributes; styles carry far lower XSS risk.
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "manifest-src 'self'",
  "frame-src 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self' https://wa.me https://api.whatsapp.com",
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
];

const headersFile = `# Generated by scripts/csp-headers.ts. Do not edit; rebuilt on every build.
/*
  ${HEADER_NAME}: ${directives.join('; ')}
`;

writeFileSync(join(OUT_DIR, '_headers'), headersFile);
console.log(
  `csp-headers: ${hashes.size} inline script hash(es) from ${htmlFiles.length} HTML file(s) -> ${OUT_DIR}/_headers (${HEADER_NAME})`,
);
